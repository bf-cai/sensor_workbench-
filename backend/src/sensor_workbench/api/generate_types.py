"""Reproducible OpenAPI-to-TypeScript generation for this API's schema subset."""

import argparse
import json
from pathlib import Path
from typing import Any

from sensor_workbench.app import create_app
from sensor_workbench.config import Settings


def _typescript(schema: dict[str, Any]) -> str:
    if "$ref" in schema:
        return str(schema["$ref"]).rsplit("/", 1)[1]
    for combination in ("anyOf", "oneOf"):
        if combination in schema:
            return " | ".join(_typescript(item) for item in schema[combination])
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(value) for value in schema["enum"])
    kind = schema.get("type")
    if kind in ("string", "number", "integer", "boolean", "null"):
        return {"integer": "number"}.get(kind, str(kind))
    if kind == "array":
        return f"ReadonlyArray<{_typescript(schema['items'])}>"
    if kind == "object":
        required = schema.get("required", [])
        properties = schema.get("properties", {})
        members = [
            f"  readonly {name}{'' if name in required else '?'}: {_typescript(value)};"
            for name, value in properties.items()
        ]
        if schema.get("additionalProperties") not in (False, None):
            raise ValueError("Open dictionaries require an explicit generator extension")
        return "{\n" + "\n".join(members) + "\n}"
    raise ValueError(f"Unsupported OpenAPI schema: {schema}")


def generate_types() -> str:
    """Generate serialization types from FastAPI's authoritative OpenAPI schema.

    Returns:
        Deterministic TypeScript text, including WebSocket schema via Health.

    Raises:
        ValueError: A new schema construct needs explicit generator support.
        OSError: Linux boot identity is unavailable when constructing the app.
    """
    schemas = create_app(Settings()).openapi()["components"]["schemas"]
    sections = [
        "// Generated by make generate-api. Do not edit manually.",
        "// Timestamp integers are lossless decimal strings in JSON.",
    ]
    for name, schema in sorted(schemas.items()):
        sections.append(f"/** {schema.get('title', name)} API serialization contract. */\n"
                        f"export type {name} = {_typescript(schema)};")
    return "\n\n".join(sections) + "\n"


def main(argv: list[str] | None = None) -> None:
    """Write generated contracts, or fail if checked-in contracts are stale.

    Args:
        argv: Command arguments; None reads process arguments.

    Raises:
        SystemExit: --check found missing or stale generated TypeScript.
    """
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    content = generate_types()
    if args.check:
        if not args.output.is_file() or args.output.read_text() != content:
            parser.exit(1, "API types are stale; run make generate-api\n")
    else:
        args.output.write_text(content, encoding="utf-8")


if __name__ == "__main__":
    main()
